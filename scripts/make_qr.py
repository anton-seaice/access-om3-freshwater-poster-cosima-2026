"""Write the docs-link QR code as TikZ squares (vector, no LaTeX QR package needed).

usage: PYTHONPATH=<dir with segno> python make_qr.py <url> <out.tex>
The output defines \\qrdocs, drawn in a unit square (y down) of size 1x1.
"""
import sys

import segno

url, out = sys.argv[1], sys.argv[2]
qr = segno.make(url, error="m")
rows = list(qr.matrix_iter(border=0))
n = len(rows)
cmds = []
for y, row in enumerate(rows):
    x = 0
    while x < n:  # merge horizontal runs of dark modules into one rectangle
        if row[x]:
            x0 = x
            while x < n and row[x]:
                x += 1
            cmds.append(f"({x0 / n:.5f},{y / n:.5f}) rectangle ({x / n:.5f},{(y + 1) / n:.5f})")
        else:
            x += 1
with open(out, "w") as f:
    f.write(f"% QR code for {url} ({n}x{n} modules), generated by scripts/make_qr.py\n")
    f.write("\\newcommand\\qrdocs{\\fill " + " ".join(cmds) + ";}\n")
print(n, "modules,", len(cmds), "rectangles")
